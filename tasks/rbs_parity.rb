require "prism"
require "rbs"

# Checks that signatures and implementations describe the same methods.
#
# Steep trusts sig/. A method declared there but never defined in lib/
# type-checks at every call site and raises NoMethodError (or an inherited
# NotImplementedError) at run time; a public method defined in lib/ with
# no signature is invisible to Steep's callers. This lint loads the
# implementation, reads the signatures through RBS's own environment, and
# compares them with Ruby reflection: existence, ownership, visibility, and
# the arguments each overload passes.
#
# A declaration counts as implemented only when the declaring class or
# module owns the method. Methods generated by Data.define or Struct.new
# live on an anonymous superclass and count as owned. A method that only an
# ancestor provides does not. Separately, a class that inherits a lib
# method whose whole body raises NotImplementedError, without overriding
# it, is reported whether or not a signature mentions it. Both rules exist
# because AppHandle#manage hid behind Manager#manage, a stub, and Window and
# Webview inherited Manager's stubs the same way.
class RbsParity
  # Ruby makes these private whatever the signature says.
  ALWAYS_PRIVATE = %i[initialize initialize_copy initialize_clone initialize_dup respond_to_missing?].freeze

  # One declared method: its visibility and its overloads (RBS functions;
  # empty for attributes and aliases, whose arguments are fixed).
  Declaration = Data.define(:visibility, :functions)

  # The positional and keyword arguments a method accepts or a signature
  # passes.
  class Shape < Data.define(:required, :optional, :rest, :required_keywords, :optional_keywords, :rest_keywords)
    # The shape of an implementation, from UnboundMethod#parameters.
    def self.from_parameters(parameters)
      kinds = parameters.group_by(&:first).transform_values { |list| list.map(&:last) }
      new(required: kinds.fetch(:req, []).size, optional: kinds.fetch(:opt, []).size, rest: kinds.key?(:rest),
        required_keywords: kinds.fetch(:keyreq, []), optional_keywords: kinds.fetch(:key, []),
        rest_keywords: kinds.key?(:keyrest))
    end

    # The shape of an RBS function.
    def self.from_function(function)
      new(required: function.required_positionals.size + function.trailing_positionals.size,
        optional: function.optional_positionals.size, rest: !function.rest_positionals.nil?,
        required_keywords: function.required_keywords.keys, optional_keywords: function.optional_keywords.keys,
        rest_keywords: !function.rest_keywords.nil?)
    end

    # Whether every call +signature+ allows is a call this implementation
    # accepts.
    def accepts?(signature)
      positional = required <= signature.required &&
        (rest || (!signature.rest && signature.required + signature.optional <= required + optional))
      keywords = (required_keywords - signature.required_keywords).empty? &&
        (rest_keywords || ((signature.required_keywords + signature.optional_keywords) -
          (required_keywords + optional_keywords)).empty?) &&
        (!signature.rest_keywords || rest_keywords)
      positional && keywords
    end
  end

  # [sig_dirs] Directories of .rbs files to read.
  # [lib_dirs] Directories whose Ruby methods need signatures.
  # [native_namespaces] Name prefixes of modules a native extension defines;
  #   their methods have no Ruby source location.
  # [allowed] Exception keys (<tt>"Tokra::Foo#bar"</tt>, <tt>"Tokra::Foo.baz"</tt>).
  # [excluded_sigs] Signature files to skip: those of another platform,
  #   whose implementation does not load here.
  def initialize(sig_dirs:, lib_dirs:, native_namespaces: [], allowed: [], excluded_sigs: [])
    @sig_dirs = sig_dirs.map { |dir| File.expand_path(dir) }
    @lib_dirs = lib_dirs.map { |dir| File.expand_path(dir) }
    @native_namespaces = native_namespaces
    @allowed = allowed
    @excluded_sigs = excluded_sigs.map { |file| File.expand_path(file) }
  end

  # The text the gate prints for +found+ violations: each one, and how to
  # allow the first in +allow_file+ when no fix is possible.
  def self.failure_message(found, allow_file)
    <<~ERROR
      ❌ Signatures and implementations disagree:
      #{found.map { |line| "  #{line}" }.join("\n")}

      Fix the signature or the implementation. Only when no fix is possible,
      add an exception with its justification to #{allow_file}:

        allow "#{found.first.to_s.split(': ').first}", lint: :rbs_parity, reason: "..."
    ERROR
  end

  # Every violation, as <tt>"key: message"</tt> lines, sorted.
  def violations
    found = declared_violations + undeclared_violations + stub_violations
    found.uniq.filter_map { |key, message| "#{key}: #{message}" unless @allowed.include?(key) }.sort
  end

  private def declared_violations
    declared.flat_map do |module_name, methods|
      target = resolve(module_name)
      next [[module_name, "declared in sig/ but not defined in lib/"]] unless target

      methods.flat_map { |(kind, name), declaration| check_declared(target, kind, name, declaration) }
    end
  end

  private def undeclared_violations
    lib_modules.flat_map do |mod|
      signatures = declared.fetch(mod.name, {})
      public_methods_of(mod).filter_map do |kind, name|
        next if signatures.key?([kind, name])
        next if kind == :singleton && generated_class_method?(mod, name)

        [key(mod.name, kind, name), "public in lib/ but has no signature"]
      end
    end
  end

  # A lib class that inherits a NotImplementedError stub from a lib module
  # or class without overriding it raises when that method is called. Its
  # public and protected instance methods and its class methods count.
  private def stub_violations
    lib_modules.grep(Class).flat_map do |klass|
      callable = [
        [:instance, klass, klass.public_instance_methods + klass.protected_instance_methods],
        [:singleton, klass.singleton_class, klass.singleton_class.public_instance_methods],
      ]
      callable.flat_map do |kind, owner, names|
        names.filter_map do |name|
          method = owner.instance_method(name)
          next if method.owner == owner || !lib_source?(method) || !stub?(method)

          [
            key(klass.name, kind, name),
            "inherited from #{describe(method.owner)}, whose #{name} only raises NotImplementedError; define it here",
          ]
        end
      end
    end
  end

  # The public methods a module owns, counting those Data.define or
  # Struct.new generated on its anonymous superclass.
  private def public_methods_of(mod)
    owners_of(mod).flat_map do |owner|
      owner.public_instance_methods(false).map { |name| [:instance, name] } +
        owner.singleton_class.public_instance_methods(false).map { |name| [:singleton, name] }
    end.uniq
  end

  private def owners_of(mod)
    owners = [mod]
    owners << owners.last.superclass while owners.last.is_a?(Class) && owners.last.superclass&.name.nil?
    owners
  end

  private def check_declared(target, kind, name, declaration)
    owner = (kind == :singleton) ? target.singleton_class : target
    label = key(target.name, kind, name)
    return check_new(target, label, declaration) if kind == :singleton && name == :new
    if kind == :instance && name == :initialize && target.is_a?(Class) && target < Data
      return [[label, "declared on a Data class; declare self.new instead (AGENTS.md)"]]
    end

    actual = visibility_of(owner, name)
    return [[label, "declared in sig/ but not defined in lib/"]] unless actual

    method = owner.instance_method(name)
    unless owns?(owner, method.owner)
      return [
[
  label,
  "declared in sig/ but only inherited from #{describe(method.owner)}; " \
    "define it here or drop the declaration",
],
]
    end

    problems = []
    # RBS has no protected; a protected method can only be declared public.
    matches = actual == declaration.visibility || (actual == :protected && declaration.visibility == :public)
    problems << [label, "#{declaration.visibility} in sig/ but #{actual} in lib/"] unless matches
    problems + arity_problems(label, Shape.from_parameters(method.parameters), declaration)
  end

  # self.new on an ordinary class runs initialize, so initialize must take
  # what each overload passes. Data.define's new takes the members,
  # positionally or by keyword, and hands them to initialize as keywords.
  private def check_new(target, label, declaration)
    return [[label, "declared in sig/ but not defined in lib/"]] unless target.is_a?(Class)

    new_method = target.singleton_class.instance_method(:new)
    initialize = target.instance_method(:initialize)
    if lib_source?(new_method)
      arity_problems(label, Shape.from_parameters(new_method.parameters), declaration)
    elsif target < Data
      data_new_problems(target, label, declaration, initialize)
    elsif owns?(target.singleton_class, new_method.owner)
      arity_problems(label, Shape.from_parameters(new_method.parameters), declaration)
    elsif owns?(target, initialize.owner)
      arity_problems(label, Shape.from_parameters(initialize.parameters), declaration)
    else
      [[label, "declared in sig/ but neither new nor initialize is defined in lib/"]]
    end
  end

  private def data_new_problems(target, label, declaration, initialize)
    members = target.members
    custom = initialize.owner != Data
    declaration.functions.filter_map do |function|
      shape = Shape.from_function(function)
      keywords = shape.required_keywords + shape.optional_keywords
      positional = shape.required + shape.optional
      fits = if custom
        positional <= members.size && (keywords - members).empty?
      elsif keywords.empty?
        positional == members.size && shape.optional.zero? && !shape.rest
      else
        positional.zero? && shape.required_keywords.sort == members.sort && shape.optional_keywords.empty?
      end
      next if fits

      [label, "overload (#{function.param_to_s}) does not match the Data members (#{members.join(', ')})"]
    end
  end

  private def arity_problems(label, implementation, declaration)
    declaration.functions.filter_map do |function|
      next if implementation.accepts?(Shape.from_function(function))

      [label, "overload (#{function.param_to_s}) passes arguments the implementation does not accept"]
    end
  end

  # Data.define and Struct.new give the class itself these reflection
  # helpers; RBS's core Data and Struct signatures already describe them.
  private def generated_class_method?(mod, name)
    mod.is_a?(Class) && (mod < Data || mod < Struct) && %i[[] members inspect keyword_init?].include?(name)
  end

  private def owns?(owner, method_owner)
    return true if method_owner == owner

    # Data.define and Struct.new build an anonymous superclass that holds
    # the generated readers and constructor.
    generated = method_owner.singleton_class? ? method_owner.attached_object : method_owner
    generated.is_a?(Class) && generated.name.nil? && owner.ancestors.include?(method_owner)
  end

  # Whether a method always ends by raising NotImplementedError: its last
  # statement is an unconditional +raise+ or +fail+ of the class, or of a
  # new instance of it, named with or without a leading <tt>::</tt>.
  private def stub?(method)
    file, line = method.source_location
    definition = definitions(file).find { |node| node.location.start_line == line && node.name == method.name }
    statements = definition&.body
    return false unless statements.is_a?(Prism::StatementsNode)

    call = statements.body.last
    return false unless call.is_a?(Prism::CallNode) && %i[raise fail].include?(call.name) && call.receiver.nil?

    error = call.arguments&.arguments&.first
    error = error.receiver if error.is_a?(Prism::CallNode) && error.name == :new
    not_implemented_error?(error)
  end

  private def not_implemented_error?(node)
    (node.is_a?(Prism::ConstantReadNode) && node.name == :NotImplementedError) ||
      (node.is_a?(Prism::ConstantPathNode) && node.full_name.delete_prefix("::") == "NotImplementedError")
  end

  private def definitions(file)
    (@definitions ||= {})[file] ||= begin
      found = []
      queue = [Prism.parse_file(file).value]
      until queue.empty?
        node = queue.shift
        found << node if node.is_a?(Prism::DefNode)
        queue.concat(node.compact_child_nodes)
      end
      found
    end
  end

  # A method owner's name; a class method's owner is the singleton class,
  # named here by the class it belongs to.
  private def describe(method_owner)
    owner = method_owner.singleton_class? ? method_owner.attached_object : method_owner
    (owner.is_a?(Module) && owner.name) || method_owner.inspect
  end

  private def visibility_of(owner, name)
    if owner.public_method_defined?(name) then :public
    elsif owner.protected_method_defined?(name) then :protected
    elsif owner.private_method_defined?(name) then :private
    end
  end

  private def lib_path?(file)
    return false unless file

    path = File.expand_path(file)
    @lib_dirs.any? { |dir| path.start_with?("#{dir}/") }
  end

  private def lib_source?(method)
    lib_path?(method.source_location&.first)
  end

  # A module is ours when a lib dir defines its constant, when a native
  # extension defined it (no source location) in one of our native
  # namespaces, or when a lib file adds a method to it (a reopened class).
  private def ours?(mod)
    file, = Object.const_source_location(mod.name)
    return true if lib_path?(file)
    return true if (file.nil? || file.empty?) && @native_namespaces.any? { |prefix| mod.name.start_with?(prefix) }

    [mod, mod.singleton_class].any? do |owner|
      (owner.instance_methods(false) + owner.private_instance_methods(false)).any? do |name|
        lib_source?(owner.instance_method(name))
      end
    end
  rescue NameError
    false
  end

  # Our named modules. A module whose constant was removed (a reloaded
  # class, or a test fixture) keeps its name but is no longer reachable by
  # it, so no signature can describe it. That check runs last, because
  # looking up a deprecated constant of someone else's prints a warning.
  private def lib_modules
    @lib_modules ||= ObjectSpace.each_object(Module).select do |mod|
      mod.name && !mod.singleton_class? && ours?(mod) && resolve(mod.name).equal?(mod)
    end
  end

  private def resolve(module_name)
    mod = Object.const_get(module_name)
    mod.is_a?(Module) ? mod : nil
  rescue NameError
    nil
  end

  private def key(module_name, kind, name)
    "#{module_name}#{(kind == :singleton) ? '.' : '#'}#{name}"
  end

  # {"Tokra::AppHandle" => {[:instance, :manage] => Declaration, ...}}
  private def declared
    @declared ||= environment.class_decls.each_with_object({}) do |(type_name, entry), result|
      decls = entry.decls.map(&:decl).select { |decl| ours_rbs?(decl) }
      next if decls.empty?

      methods = result[type_name.to_s.delete_prefix("::")] = {}
      decls.each { |decl| collect_members(decl.members, methods) }
    end
  end

  private def ours_rbs?(decl)
    path = File.expand_path(decl.location.buffer.name.to_s)
    @sig_dirs.any? { |dir| path.start_with?("#{dir}/") }
  end

  private def collect_members(members, methods)
    default = :public
    members.each do |member|
      case member
      when RBS::AST::Members::Private then default = :private
      when RBS::AST::Members::Public then default = :public
      when RBS::AST::Members::MethodDefinition then add_method(methods, member, default)
      when RBS::AST::Members::AttrReader, RBS::AST::Members::AttrWriter, RBS::AST::Members::AttrAccessor
        add_attribute(methods, member, default)
      when RBS::AST::Members::Include then add_interface(methods, member)
      when RBS::AST::Members::Alias
        methods[[(member.kind == :singleton) ? :singleton : :instance, member.new_name]] = Declaration.new(default, [])
      end
    end
  end

  private def functions_of(member)
    member.overloads.map { |overload| overload.method_type.type }.grep(RBS::Types::Function)
  end

  private def add_method(methods, member, default)
    visibility = member.visibility || default
    kinds = case member.kind
    when :singleton then [:singleton]
    when :singleton_instance then %i[singleton instance]
    else [:instance]
    end
    kinds.each do |kind|
      private_instance = kind == :instance && (member.kind == :singleton_instance || ALWAYS_PRIVATE.include?(member.name))
      methods[[kind, member.name]] = Declaration.new(private_instance ? :private : visibility, functions_of(member))
    end
  end

  # Including an interface declares its methods on the class.
  private def add_interface(methods, member)
    return unless member.name.interface?

    entry = environment.interface_decls[member.name] or return
    entry.decl.members.grep(RBS::AST::Members::MethodDefinition).each do |interface_member|
      name = interface_member.name
      visibility = ALWAYS_PRIVATE.include?(name) ? :private : :public
      methods[[:instance, name]] = Declaration.new(visibility, functions_of(interface_member))
    end
  end

  private def add_attribute(methods, member, default)
    kind = (member.kind == :singleton) ? :singleton : :instance
    declaration = Declaration.new(member.visibility || default, [])
    methods[[kind, member.name]] = declaration unless member.is_a?(RBS::AST::Members::AttrWriter)
    methods[[kind, :"#{member.name}="]] = declaration unless member.is_a?(RBS::AST::Members::AttrReader)
  end

  # Every .rbs file under the signature directories, less the excluded.
  private def signature_files
    @sig_dirs.flat_map { |dir| Dir.glob("**/*.rbs", base: dir).sort.map { |file| File.join(dir, file) } }
      .reject { |file| @excluded_sigs.include?(file) }
  end

  private def environment
    @environment ||= load_environment
  end

  private def load_environment
    # Only our own declarations matter, so skip RBS core and stdlib.
    loader = RBS::EnvironmentLoader.new(core_root: nil)
    signature_files.each { |file| loader.add(path: Pathname(file)) }
    RBS::Environment.from_loader(loader).resolve_type_names
  end
end

# Run as a script: load every file in the lib dirs, then report.
#   ruby tasks/rbs_parity.rb --sig sig --lib lib --native Tokra::Native \
#     --allow rbs_exceptions.rb --exclude-sig sig/tokra/activation_policy.rbs
if $PROGRAM_NAME == __FILE__
  require "optparse"
  require_relative "lint"

  options = { sig: [], lib: [], native: [], allow: nil, exclude: [] }
  OptionParser.new do |parser|
    parser.on("--sig DIR") { |dir| options[:sig] << dir }
    parser.on("--lib DIR") { |dir| options[:lib] << dir }
    parser.on("--native PREFIX") { |prefix| options[:native] << prefix }
    parser.on("--allow FILE") { |file| options[:allow] = file }
    parser.on("--exclude-sig FILE") { |file| options[:exclude] << file }
  end.parse!

  options[:lib].each { |dir| $LOAD_PATH.unshift(File.expand_path(dir)) }
  options[:lib].each do |dir|
    Dir.glob("**/*.rb", base: dir).sort.each { |file| require File.expand_path(file, dir) }
  end

  allowed = options[:allow] ? Lint.load(options[:allow]).keys(lint: :rbs_parity) : []
  found = RbsParity.new(sig_dirs: options[:sig], lib_dirs: options[:lib],
    native_namespaces: options[:native], allowed:, excluded_sigs: options[:exclude]).violations
  abort RbsParity.failure_message(found, options[:allow]) if found.any?

  puts "✅ Every signature has an implementation and every public method a signature"
end
